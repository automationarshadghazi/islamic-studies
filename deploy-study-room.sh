#!/usr/bin/env bash
# Study Room deployment: compiled WinSCP upload -> Nginx on loopback TCP 9001.
# Root is required for a real installation. --dry-run makes no system changes.
set -Eeuo pipefail
umask 022
PORT=9001
SOURCE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
DOMAIN=''
FREE_PORT=0
ASSUME_YES=0
DRY_RUN=0
ROOT=/var/www/study-room
CONFIG=/etc/nginx/conf.d/study-room-9001.conf
MARKER='# Managed by deploy-study-room.sh'
BACKUP=''
PREVIOUS_LINK=''
HAD_CONFIG=0
CHANGED=0
HEALTHY=0
STAGE=''
DUMP=''
log() { printf '\n[study-room] %s\n' "$*"; }
fail() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }
usage() {
  cat <<'HELP'
Usage: sudo bash deploy-study-room.sh --domain revise.your-domain.com [options]
  --source DIR  Folder containing the extracted index.html and content.json.
                Default: the folder beside this script (not the Git source).
  --domain HOST Your subdomain. Produces a proxy snippet; does NOT edit its site.
  --free-port   Permit stopping a conflicting listener on TCP 9001, after review.
  --yes         Skip the interactive STOP-9001 confirmation (requires --free-port).
  --dry-run     Validate upload and print plan; no installs, kills or config edits.
  --help        Show this help.

Supported installers: apt-get (Debian/Ubuntu) and dnf (Fedora/Rocky/Alma).
No Node, npm, pip, database or application daemon is required for the ready build.
Nginx serves it on 127.0.0.1:9001. Your existing HTTPS subdomain proxies to it.
Protected/shared processes (including an unrelated Nginx listener) are NOT killed.
Existing site configurations and certificates are never overwritten.
HELP
}
while (($#)); do
  case "$1" in
    --source|--domain)
      (($# >= 2)) || fail "Missing value for $1"
      if [[ "$1" == --source ]]; then SOURCE=$2; else DOMAIN=$2; fi
      shift 2 ;;
    --free-port) FREE_PORT=1; shift ;;
    --yes) ASSUME_YES=1; shift ;;
    --dry-run) DRY_RUN=1; shift ;;
    --help|-h) usage; exit 0 ;;
    *) fail "Unknown option: $1 (use --help)" ;;
  esac
done
[[ $ASSUME_YES == 0 || $FREE_PORT == 1 ]] || fail '--yes requires --free-port.'
# Restrict domain to DNS labels, never shell/nginx directives or URLs.
[[ ${#DOMAIN} -le 253 && "$DOMAIN" == *.* && "$DOMAIN" =~ ^[a-zA-Z0-9]([a-zA-Z0-9.-]*[a-zA-Z0-9])?$ ]] || fail 'Use --domain with a hostname only, e.g. revise.your-domain.com (not https:// or a path).'
[[ "$DOMAIN" != *..* ]] || fail 'Domain has an empty DNS label.'
IFS=. read -r -a labels <<< "$DOMAIN"
for label in "${labels[@]}"; do
  [[ ${#label} -le 63 && "$label" != -* && "$label" != *- ]] || fail 'Invalid DNS label.'
done
[[ -d "$SOURCE" ]] || fail "Upload folder not found: $SOURCE"
SOURCE=$(cd -- "$SOURCE" && pwd -P)
[[ "$SOURCE" != "$ROOT" && "$SOURCE" != "$ROOT/"* ]] || fail 'Upload to a separate staging folder, not the live /var/www/study-room tree.'
for item in index.html app.js study-core.js styles.css content.json favicon.svg SHA256SUMS; do
  [[ -f "$SOURCE/$item" && ! -L "$SOURCE/$item" ]] || fail "Missing upload file: $item. Use the NEW website ZIP; do not upload website/ or the source-code ZIP alone."
done
[[ -d "$SOURCE/downloads" && ! -L "$SOURCE/downloads" ]] || fail 'Missing downloads/ directory.'
[[ -z "$(find "$SOURCE/downloads" -type l -print -quit)" ]] || fail 'Symlinks are not permitted inside downloads/.'
# Only allow exact relative names generated by the packager in the checksum list.
while IFS= read -r checksum; do
  [[ "$checksum" =~ ^[a-f0-9]{64}\ \ (index\.html|app\.js|study-core\.js|styles\.css|content\.json|favicon\.svg|downloads/[a-zA-Z0-9_.-]+)$ ]] || fail 'Unexpected or unsafe entry in SHA256SUMS.'
  file=${checksum:66}
  [[ -f "$SOURCE/$file" && ! -L "$SOURCE/$file" ]] || fail "Missing/nonregular public file: $file"
done < "$SOURCE/SHA256SUMS"
# Presence alone is not verification: every published file must be listed exactly once.
for item in index.html app.js study-core.js styles.css content.json favicon.svg; do
  [[ $(grep -Fc "  $item" "$SOURCE/SHA256SUMS") == 1 ]] || fail "Missing/duplicate checksum for $item."
done
[[ $(grep -c '  downloads/' "$SOURCE/SHA256SUMS") -eq 9 ]] || fail 'Expected checksums for all nine authored downloads.'
[[ $(cut -c 67- "$SOURCE/SHA256SUMS" | sort -u | wc -l) -eq 15 ]] || fail 'Checksum list has missing/duplicate entries.'
if command -v sha256sum >/dev/null; then
  (cd -- "$SOURCE" && sha256sum --check --status SHA256SUMS) || fail 'Upload checksum failed. Re-upload in WinSCP Binary mode; do not edit/convert the compiled files.'
else
  [[ $DRY_RUN == 0 ]] || fail 'sha256sum is missing; a real install installs coreutils.'
fi
if [[ $DRY_RUN == 1 ]]; then
  log "DRY RUN: validated upload at $SOURCE"
  printf '%s\n' 'Will install missing nginx, curl, lsof, iproute, procps, coreutils and util-linux only.' \
    'Will verify Nginx, inspect TCP 9001 and require permission before freeing conflicts.' \
    "Will stage a read-only public release under $ROOT and activate $CONFIG." \
    'Will test Nginx, reload without restarting other sites, and health-check loopback 9001.' \
    "Will generate a proxy snippet for $DOMAIN; existing HTTPS/subdomain configuration is left alone."
  if command -v ss >/dev/null; then ss -ltnp 'sport = :9001'; fi
  exit 0
fi
((EUID == 0)) || fail 'Run with sudo bash deploy-study-room.sh ...'
# Refuse symlinked installation/config targets instead of writing through them.
[[ ! -L "$ROOT" && ! -L "$CONFIG" ]] || fail 'Installation root or managed config is a symlink; review manually.'
missing=()
for cmd in nginx curl lsof ss ps pgrep sha256sum flock; do
  command -v "$cmd" >/dev/null || missing+=("$cmd")
done
if ((${#missing[@]})); then
  log "Installing prerequisites (missing commands: ${missing[*]})."
  # Linux /proc works even if procps/pgrep is one of the missing packages.
  if [[ " ${missing[*]} " == *" nginx "* ]]; then
    for commfile in /proc/[0-9]*/comm; do
      if IFS= read -r process 2>/dev/null < "$commfile"; then
        [[ "$process" != nginx ]] || fail 'Nginx is already running outside PATH. Add its correct executable to root PATH instead of installing a second Nginx.'
      fi
    done
  fi
  # Install only packages for unavailable commands, not the whole list: a missing
  # lsof must never trigger an unintended upgrade/restart of existing Nginx.
  declare -A packages=([nginx]=nginx [curl]=curl [lsof]=lsof [ss]=iproute2 [ps]=procps [pgrep]=procps [sha256sum]=coreutils [flock]=util-linux)
  manager=apt-get
  if ! command -v apt-get >/dev/null; then
    command -v dnf >/dev/null || fail 'No supported package manager. Install nginx curl lsof iproute/procps coreutils util-linux, then rerun.'
    manager=dnf; packages[ss]=iproute; packages[ps]=procps-ng; packages[pgrep]=procps-ng
  fi
  wanted=()
  for cmd in "${missing[@]}"; do wanted+=("${packages[$cmd]}"); done
  if [[ ! -f /etc/ssl/certs/ca-certificates.crt && ! -f /etc/pki/tls/certs/ca-bundle.crt ]]; then wanted+=(ca-certificates); fi
  mapfile -t wanted < <(printf '%s\n' "${wanted[@]}" | sort -u)
  if [[ "$manager" == apt-get ]]; then
    apt-get update
    DEBIAN_FRONTEND=noninteractive NEEDRESTART_MODE=l apt-get install -y --no-upgrade --no-install-recommends "${wanted[@]}"
  else
    dnf install -y "${wanted[@]}"
  fi
fi
for cmd in nginx curl lsof ss ps pgrep sha256sum flock; do command -v "$cmd" >/dev/null || fail "Dependency still unavailable: $cmd"; done
(cd -- "$SOURCE" && sha256sum --check --status SHA256SUMS) || fail 'Upload checksum failed.'
mkdir -p /run/lock
exec 9>/run/lock/study-room-deploy.lock
flock -n 9 || fail 'Another Study Room deployment is running.'
nginx -t || fail 'Existing Nginx config is invalid. Fix it before deploying; nothing has been replaced.'
if [[ -e "$CONFIG" ]]; then
  grep -Fxq "$MARKER" "$CONFIG" || fail "Refusing to overwrite an unrecognised config: $CONFIG"
  HAD_CONFIG=1
fi
[[ ! -e "$ROOT/current" || -L "$ROOT/current" ]] || fail "$ROOT/current is a real directory. Move your old manual installation aside before deploying."
if [[ -L "$ROOT/current" ]]; then PREVIOUS_LINK=$(readlink -- "$ROOT/current"); fi
STAMP="$(date -u +%Y%m%dT%H%M%SZ)-$$"
BACKUP="/var/backups/study-room/$STAMP"
install -d -m 0700 "$BACKUP"
if ((HAD_CONFIG)); then cp -p -- "$CONFIG" "$BACKUP/nginx.conf"; fi
printf '%s\n' "$PREVIOUS_LINK" > "$BACKUP/previous-current.txt"
reload_nginx() {
  if command -v systemctl >/dev/null && [[ -d /run/systemd/system ]]; then
    if systemctl is-active --quiet nginx; then systemctl reload nginx
    elif pgrep -x nginx >/dev/null; then nginx -s reload
    else systemctl enable --now nginx; fi
  elif pgrep -x nginx >/dev/null; then nginx -s reload
  else nginx
  fi
}
cleanup() {
  local status=$?
  trap - EXIT INT TERM
  if ((status != 0 && CHANGED == 1 && HEALTHY == 0)); then
    printf '\nDeployment failed; restoring the previous managed configuration and release link.\n' >&2
    if ((HAD_CONFIG)); then cp -p -- "$BACKUP/nginx.conf" "$CONFIG"; else rm -f -- "$CONFIG"; fi
    if [[ -n "$PREVIOUS_LINK" ]]; then
      ln -s -- "$PREVIOUS_LINK" "$ROOT/.restore-$$" && mv -Tf -- "$ROOT/.restore-$$" "$ROOT/current"
    elif [[ -L "$ROOT/current" ]]; then rm -f -- "$ROOT/current"; fi
    if nginx -t; then reload_nginx || printf 'WARNING: manual Nginx reload required.\n' >&2; fi
    printf 'Previously stopped conflicting services/processes are NOT automatically restarted. Review the deployment log.\n' >&2
  fi
  [[ -z "$DUMP" ]] || rm -f -- "$DUMP"
  [[ -z "$STAGE" || ! -e "$STAGE" ]] || rm -f -- "$STAGE"
  exit "$status"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
# Render/validate release before stopping anyone. Copy only public files, never this
# installer, notes source, shell files, .git or server configurations.
RELEASE="$ROOT/releases/$STAMP"
install -d -m 0755 "$ROOT" "$ROOT/releases" "$RELEASE"
for file in index.html app.js study-core.js styles.css content.json favicon.svg; do install -m 0644 "$SOURCE/$file" "$RELEASE/$file"; done
install -d -m 0755 "$RELEASE/downloads"
# Copy only checksummed public downloads; ignore unexpected extra uploaded files.
while IFS= read -r checksum; do
  file=${checksum:66}
  if [[ "$file" == downloads/* ]]; then install -m 0644 "$SOURCE/$file" "$RELEASE/$file"; fi
done < "$SOURCE/SHA256SUMS"
find "$RELEASE" -type d -exec chmod 0755 {} +
find "$RELEASE" -type f -exec chmod 0644 {} +
[[ -d /etc/nginx/conf.d ]] || fail "Your Nginx does not have /etc/nginx/conf.d. Set up that include directory in http{} and rerun."
STAGE=$(mktemp /etc/nginx/conf.d/.study-room-XXXXXX)
cat > "$STAGE" <<NGINX
$MARKER
# Backend is private. Proxy your existing HTTPS subdomain to 127.0.0.1:$PORT.
server {
    listen 127.0.0.1:$PORT;
    server_name _;
    root $ROOT/current;
    index index.html;
    server_tokens off;
    charset utf-8;
    include /etc/nginx/mime.types;
    default_type application/octet-stream;
    add_header X-Study-Room-Backend managed-9001 always;
    add_header X-Content-Type-Options nosniff always;
    add_header Referrer-Policy strict-origin-when-cross-origin always;
    add_header Cache-Control "no-cache" always;
    gzip on;
    gzip_vary on;
    gzip_types text/css application/javascript application/json text/plain;
    location / { try_files \$uri \$uri/ =404; }
    location ~ /\. { deny all; }
}
NGINX
# SELinux requires permission for a nonstandard HTTP port and a public content root.
if command -v getenforce >/dev/null && [[ $(getenforce) == Enforcing ]]; then
  if ! command -v semanage >/dev/null; then
    if command -v dnf >/dev/null; then dnf install -y policycoreutils-python-utils; fi
  fi
  command -v semanage >/dev/null || fail 'SELinux Enforcing: install semanage and assign TCP 9001 to http_port_t, then rerun.'
  command -v restorecon >/dev/null || fail 'SELinux Enforcing: restorecon is required (policycoreutils). Install it and rerun.'
  # Refuse to re-label a port belonging to another service's SELinux type.
  if ! semanage port -l | awk '$1=="http_port_t" && $2=="tcp" { for(i=3;i<=NF;i++){gsub(",","",$i);split($i,r,"-");if((r[1]+0==9001)||(r[2]!=""&&r[1]+0<=9001&&r[2]+0>=9001))found=1}} END{exit !found}'; then
    semanage port -a -t http_port_t -p tcp "$PORT" || fail 'SELinux port 9001 already has another type; review it manually instead of relabelling blindly.'
  fi
  if ! semanage fcontext -a -t httpd_sys_content_t "$ROOT(/.*)?"; then semanage fcontext -m -t httpd_sys_content_t "$ROOT(/.*)?"; fi
  restorecon -RF "$ROOT"
fi
listeners() { lsof -nP -t -iTCP:"$PORT" -sTCP:LISTEN 2>/dev/null | sort -un || true; }
mapfile -t PIDS < <(listeners)
NEED_STOP=()
declare -A UNITS IDENTITIES
for pid in "${PIDS[@]}"; do
  [[ "$pid" =~ ^[0-9]+$ ]] || fail "Invalid listener PID: $pid"
  comm=$(ps -p "$pid" -o comm= | tr -d '[:space:]')
  # Updating OUR already-running Nginx listener only needs a graceful reload.
  if [[ "$comm" == nginx && $HAD_CONFIG == 1 ]] && curl --noproxy '*' -fsSI --max-time 2 "http://127.0.0.1:$PORT/" | grep -iq '^X-Study-Room-Backend: managed-9001'; then continue; fi
  case "$comm" in
    nginx|sshd|systemd|init|docker*|containerd*|caddy|apache2|httpd)
      fail "Port $PORT is held by protected/shared process $comm (PID $pid). Inspect with: sudo ss -ltnp 'sport = :9001'. Remove only that listener/container mapping manually; this script will not stop all Nginx/SSH/container services." ;;
  esac
  [[ -n "$comm" ]] || fail "Listener PID $pid disappeared during inspection; rerun."
  [[ "$pid" != 1 && "$pid" != "$$" && "$pid" != "$PPID" ]] || fail 'Refusing to stop an essential/current process.'
  unit=$(ps -p "$pid" -o unit= | tr -d '[:space:]')
  case "$unit" in
    nginx.service|ssh.service|sshd.service|docker.service|containerd.service|systemd*|dbus.service|cron*.service|supervisor*.service|pm2*.service|*.socket)
      fail "Protected or socket-activated unit: $unit; disable only its conflicting listener manually." ;;
  esac
  UNITS[$pid]=$unit
  IDENTITIES[$pid]=$(ps -p "$pid" -o lstart=,args=)
  NEED_STOP+=("$pid")
done
if ((${#NEED_STOP[@]})); then
  log 'Conflicting listeners on TCP 9001:'
  lsof -nP -iTCP:"$PORT" -sTCP:LISTEN
  ((FREE_PORT == 1)) || fail 'Nothing was stopped. Rerun with --free-port to authorise stopping these listeners.'
  if ((ASSUME_YES == 0)); then
    [[ -t 0 ]] || fail 'Interactive confirmation requires a terminal. Review the PIDs, then use --free-port --yes only if intended.'
    read -r -p 'Type STOP-9001 to stop these listeners (may interrupt another app): ' answer
    [[ "$answer" == STOP-9001 ]] || fail 'Cancelled; nothing stopped.'
  fi
  # A systemd unit can own a respawning process. Stop the exact unit, not all services.
  for pid in "${NEED_STOP[@]}"; do
    unit=${UNITS[$pid]}
    # Do not stop a replacement process that reused a PID after inspection.
    [[ "$(ps -p "$pid" -o lstart=,args=)" == "${IDENTITIES[$pid]}" ]] || fail "Listener PID $pid changed during review; rerun and inspect it again."
    ps -p "$pid" -o pid=,ppid=,user=,unit=,args= >> "$BACKUP/stopped-listeners.txt"
    if [[ "$unit" == *.service && "$unit" != user@*.service && -d /run/systemd/system ]]; then
      log "Stopping unit $unit (PID $pid); it is not disabled."
      systemctl stop "$unit"
    elif kill -0 "$pid" 2>/dev/null; then
      log "Sending TERM to PID $pid (not a process group)."
      kill -TERM "$pid"
    fi
  done
  for _ in {1..20}; do
    remaining=$(listeners)
    [[ -z "$remaining" ]] && break
    sleep 0.25
  done
  # Do not escalate to SIGKILL or chase new PIDs from a supervisor automatically.
  [[ -z "$(listeners)" ]] || fail 'TCP 9001 is still occupied or was respawned. Stop its owning supervisor/container manually; no SIGKILL was sent.'
fi
log 'Activating the managed release and Nginx backend.'
CHANGED=1
ln -s -- "$RELEASE" "$ROOT/.next-$$"
mv -Tf -- "$ROOT/.next-$$" "$ROOT/current"
install -m 0644 "$STAGE" "$CONFIG"
if command -v getenforce >/dev/null && [[ $(getenforce) == Enforcing ]]; then restorecon -RF "$ROOT"; fi
nginx -t
DUMP=$(mktemp)
chmod 0600 "$DUMP"
nginx -T > "$DUMP" 2>&1
# Some custom Nginx installations do not include conf.d at all.
grep -Fq "configuration file $CONFIG:" "$DUMP" || fail 'Your nginx.conf does not include this conf.d file. Add include /etc/nginx/conf.d/*.conf inside http{}, then rerun.'
reload_nginx
# A graceful reload is asynchronous; wait for both the new HTML AND new data.
EXPECTED_HTML=$(sha256sum "$RELEASE/index.html" | awk '{print $1}')
EXPECTED_DATA=$(sha256sum "$RELEASE/content.json" | awk '{print $1}')
ready=0
for _ in {1..30}; do
  if html=$(curl --noproxy '*' -fsS --max-time 2 "http://127.0.0.1:$PORT/" | sha256sum | awk '{print $1}') && \
     json=$(curl --noproxy '*' -fsS --max-time 2 "http://127.0.0.1:$PORT/content.json" | sha256sum | awk '{print $1}') && \
     [[ "$html" == "$EXPECTED_HTML" && "$json" == "$EXPECTED_DATA" ]]; then ready=1; break; fi
  sleep 0.25
done
((ready == 1)) || fail 'Health check did not return the deployed HTML/data. Rollback will run.'
# Save instructions OUTSIDE conf.d so Nginx cannot accidentally include them.
SNIPPET="$BACKUP/subdomain-location.txt"
cat > "$SNIPPET" <<PROXY
# In the EXISTING HTTPS server{} for $DOMAIN, replace its existing location / block
# with this one (do not create duplicate location / blocks; keep TLS settings).
location / {
    proxy_pass http://127.0.0.1:9001;
    proxy_http_version 1.1;
    proxy_cache off;
    proxy_set_header Host \$host;
    proxy_set_header X-Real-IP \$remote_addr;
    proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto \$scheme;
}
# Test with sudo nginx -t, THEN sudo systemctl reload nginx.
PROXY
HEALTHY=1
log "SUCCESS: private backend is serving http://127.0.0.1:$PORT/"
printf '\n%s\n' "Release: $RELEASE" "Backups: $BACKUP" "Subdomain snippet: $SNIPPET"
printf '\nYour existing domain and certificates were NOT edited.\n'
cat "$SNIPPET"
printf '\nDo not open public firewall port 9001: Nginx on your HTTPS subdomain proxies locally.\nOn SELinux systems, your public proxy may also require the httpd_can_network_connect policy.
Keep exported drafts safe: local browser progress does not migrate between domains.\n'
